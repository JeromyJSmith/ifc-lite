/**
 * Generates the TYPED attribute table for entity classes that exist in the
 * IFC4X3 schema but not in the parser's IFC4_ADD2_TC1 codegen pin.
 *
 * The parser's `getAttributeNamesAcrossSchemas` already resolves attribute
 * NAMES for these classes (from `@ifc-lite/data`'s IDS-derived tables), but
 * those tables carry no attribute TYPES — so the STEP exporter's unit
 * normalization silently saw an empty attribute list for IFC4.3 classes and
 * left their lengths unscaled. This table closes that gap from the SAME
 * source of truth the pin itself came from: the committed codegen output of
 * the IFC4X3 EXPRESS schema
 * (`packages/codegen/generated/ifc4x3/schema-registry.ts`).
 * (SELECT-slot qualification is NOT wired to it: every scalar SELECT slot on
 * an IFC4X3-delta class is either an entity-only select or ambiguous by
 * design, so there is nothing for the auto-qualifier to resolve.)
 *
 * Only the DELTA is emitted (entities in IFC4X3 and not in IFC4): for every
 * shared entity the pinned registry stays authoritative, which is safe
 * because the sole measure-relevant divergence between the two registries is
 * `IfcSweptDiskSolidPolygonal.FilletRadius` moving from IfcPositiveLengthMeasure
 * to IfcNonNegativeLengthMeasure — same slot, same length dimension.
 *
 * Regenerate after a codegen/schema change:
 *   node scripts/generate-union-attr-types.mjs
 * `--check` compares the committed file against a fresh derivation and exits
 * 1 on drift (CI: node-tests job).
 *
 * Output: packages/parser/src/generated/attr-types-union.ts
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CHECK = process.argv.includes('--check');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Extract and evaluate the `SCHEMA_REGISTRY` object literal from a generated
 * registry .ts file. The literal is plain JS (string/boolean/array/object
 * values only); the balanced-brace scan honours quoted strings so a bracketed
 * EXPRESS type string can never derail it.
 */
function loadRegistry(relPath) {
  const src = readFileSync(join(root, relPath), 'utf8');
  const marker = 'export const SCHEMA_REGISTRY: SchemaRegistry = {';
  const start = src.indexOf(marker);
  if (start === -1) throw new Error(`SCHEMA_REGISTRY literal not found in ${relPath}`);
  const open = start + marker.length - 1;
  let depth = 0;
  let inString = null; // the active quote char, or null
  for (let i = open; i < src.length; i++) {
    const ch = src[i];
    if (inString) {
      if (ch === '\\') i++;
      else if (ch === inString) inString = null;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === '`') { inString = ch; continue; }
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) {
        const literal = src.slice(open, i + 1);
        return new Function(`return (${literal});`)();
      }
    }
  }
  throw new Error(`Unbalanced SCHEMA_REGISTRY literal in ${relPath}`);
}

const ifc4 = loadRegistry('packages/codegen/generated/ifc4/schema-registry.ts');
const ifc4x3 = loadRegistry('packages/codegen/generated/ifc4x3/schema-registry.ts');

const pinnedUpper = new Set(Object.keys(ifc4.entities).map((k) => k.toUpperCase()));

// flags bitfield: 1 = optional, 2 = isArray, 4 = isList, 8 = isSet.
const flagsOf = (a) => (a.optional ? 1 : 0) | (a.isArray ? 2 : 0) | (a.isList ? 4 : 0) | (a.isSet ? 8 : 0);

const rows = Object.values(ifc4x3.entities)
  .filter((e) => !pinnedUpper.has(e.name.toUpperCase()))
  .sort((a, b) => (a.name < b.name ? -1 : 1))
  .map((e) => {
    const attrs = (e.allAttributes ?? [])
      .map((a) => `[${JSON.stringify(a.name)}, ${JSON.stringify(a.type)}, ${flagsOf(a)}]`)
      .join(', ');
    return `  ${e.name.toUpperCase()}: [${attrs}],`;
  });

const out = `/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/. */

/**
 * TYPED attributes (STEP positional order, inherited included) for the entity
 * classes of the IFC4X3 schema that are OUTSIDE the parser's IFC4_ADD2_TC1
 * codegen pin. Complements the names-only tables in \`@ifc-lite/data\`: names
 * answer "what is slot 7 called", these rows also answer "what EXPRESS type
 * is slot 7", which the exporter's unit normalization needs.
 *
 * Each row is \`[name, type, flags]\`; flags bitfield:
 * 1 = optional, 2 = isArray, 4 = isList, 8 = isSet.
 *
 * DO NOT EDIT — generated by \`node scripts/generate-union-attr-types.mjs\`
 * from \`packages/codegen/generated/ifc4x3/schema-registry.ts\`.
 */

export type UnionAttrRow = readonly [name: string, type: string, flags: number];

export const IFC4X3_DELTA_ATTR_TYPES: Readonly<Record<string, readonly UnionAttrRow[]>> = {
${rows.join('\n')}
};
`;

const OUT_PATH = join(root, 'packages/parser/src/generated/attr-types-union.ts');

if (CHECK) {
  let committed;
  try {
    committed = readFileSync(OUT_PATH, 'utf8');
  } catch {
    console.error('attr-types-union.ts is missing. Run `node scripts/generate-union-attr-types.mjs` and commit it.');
    process.exit(1);
  }
  if (committed !== out) {
    console.error('attr-types-union.ts drifted from the codegen registries. Run `node scripts/generate-union-attr-types.mjs` and commit the result.');
    process.exit(1);
  }
  console.log(`attr-types-union.ts is in sync (${rows.length} IFC4X3-delta entities).`);
} else {
  writeFileSync(OUT_PATH, out);
  console.log(`Wrote packages/parser/src/generated/attr-types-union.ts (${rows.length} IFC4X3-delta entities).`);
}
